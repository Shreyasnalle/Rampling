export interface TypewriterWordProps {
  words?: string[];
  typingSpeed?: number;
  deletingSpeed?: number;
  pauseDuration?: number;
  className?: string;
  style?: React.CSSProperties;
  cursorClassName?: string;
}

export const TypewriterWord = ({
  words = ["performs", "scales", "breaks", "responds"],
  typingSpeed = 110,
  deletingSpeed = 60,
  pauseDuration = 2000,
  className,
  style,
  cursorClassName,
}: TypewriterWordProps) => {
  const [wordIndex, setWordIndex] = useState(0);
  const [currentText, setCurrentText] = useState("");
  const [isDeleting, setIsDeleting] = useState(false);

  useEffect(() => {
    if (!words || words.length === 0) return;
    const currentFullWord = words[wordIndex % words.length];

    let timer: NodeJS.Timeout;

    if (!isDeleting) {
      if (currentText.length < currentFullWord.length) {
        timer = setTimeout(() => {
          setCurrentText(currentFullWord.slice(0, currentText.length + 1));
        }, typingSpeed);
      } else {
        timer = setTimeout(() => {
          setIsDeleting(true);
        }, pauseDuration);
      }
    } else {
      if (currentText.length > 0) {
        timer = setTimeout(() => {
          setCurrentText(currentFullWord.slice(0, currentText.length - 1));
        }, deletingSpeed);
      } else {
        setIsDeleting(false);
        setWordIndex((prev: number) => (prev + 1) % words.length);
      }
    }

    return () => clearTimeout(timer);
  }, [currentText, isDeleting, wordIndex, words, typingSpeed, deletingSpeed, pauseDuration]);

  return (
    <span className="inline-flex items-baseline whitespace-nowrap">
      <span className={cn("inline-block", className)} style={style}>
        {currentText || "\u200B"}
      </span>
      <span
        aria-hidden="true"
        className={cn(
          "inline-block w-[2.5px] sm:w-[3.5px] h-[0.78em] ml-1 bg-[#7cff67] rounded-xs animate-pulse self-center",
          cursorClassName
        )}
      />
    </span>
  );
};
